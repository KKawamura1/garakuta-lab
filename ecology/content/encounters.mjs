// 敵の表示名から「種別の呼び名」を引く表。`灰殻の走者` → `走者`。
// 遭遇の説明文が、実際に出ない敵を名指ししていないかを機械的に見るために使う
// （analysis/ecology-readout-smoke.mjs）。同じ呼び名を二つの個体が持たない。
export const ENEMY_SHORT_NAMES = Object.freeze(
  Object.fromEntries(ENEMY_UNITS.map((unit) => {
    const index = unit.name.indexOf("の");
    return [unit.id, index > 0 ? unit.name.slice(index + 1) : unit.name];
  })),
);

export function enemyShortName(enemyActorId) {
  return ENEMY_SHORT_NAMES[enemyActorId] ?? ENEMY_UNIT_BY_ID[enemyActorId]?.name ?? enemyActorId;
}
