const REACTIVE_PHRASE = Object.freeze({
  counter_blow: "殴られると、反応点1で殴り返す",
  cover_ally: "自分以外の味方が狙われると、反応点1で身代わりになる",
  mend: "味方が傷つくと、反応点1でその傷を手当てする",
});

export function enemyTargetingFor(unit) {
  const phrases = unit.tactics.map((skillId) => {
    const phrase = TACTIC_PHRASE[skillId];
    if (!phrase) throw new Error("encounters: 狙いの言い換えが無い行動技能 " + skillId);
    return phrase;
  });
  const sentences = [];
  if (phrases.length === 1) {
    sentences.push(phrases[0]);
  } else {
    phrases.forEach((phrase, index) => {
      if (index === 0) sentences.push(phrase);
      else if (index < phrases.length - 1) sentences.push("通らなければ" + phrase);
      else sentences.push((phrases.length > 2 ? "それも通らなければ" : "通らなければ") + phrase);
    });
  }
  if ((unit.ap ?? 1) >= 2) sentences.push("一巡に" + (unit.ap === 2 ? "二" : String(unit.ap)) + "度動く");
  for (const reactiveId of unit.reactives ?? []) {
    const phrase = REACTIVE_PHRASE[reactiveId];
    if (!phrase) throw new Error("encounters: 反応技能の言い換えが無い " + reactiveId);
    sentences.push(phrase);
  }
  return sentences.join("。") + "。";
}

export const ENEMY_TARGETING = Object.freeze(
  Object.fromEntries(ENEMY_UNITS.map((unit) => [unit.id, enemyTargetingFor(unit)])),
);

