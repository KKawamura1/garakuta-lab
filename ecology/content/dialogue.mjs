// **会話定義の正本。**本編の物語、序盤の一戦、根城の日常場面で
// 表示する台詞と地の文を、ここへ一箇所に集約する。
//
// 会話の本文や配役を変えるときは、このファイルだけを編集する。story.mjs と
// homestead.mjs には舞台・条件・表示順だけを置き、本文と表示条件が
// 同じ行に混ざらないようにする。
//
// タイトル、場所、立ち位置、解禁条件、説明用 footer / hint、名簿の設定文は
// 会話本文ではないため、それぞれの定義ファイルに残す。
//
// ---------------------------------------------------------------- R13 で全面的に書き直した
//
// 人物が5人とも入れ替わったので、28本すべてを書き直している
// （設計は `analysis/CAST_REBOOT_TWELVE_TOMORROWS.md`）。
//
// **台詞は長く、会話は短く。**往復を増やさずに、一人の台詞へ情報を二つ三つ積む。
// 短い応酬だけで組むと、読み味は軽いが**何も伝わらない会話**になる。
//
// **行数のハードリミットは置かない（R13・作者判断）。**数で縛ると、一行に情報を
// 詰められない場面まで一律に切り詰めることになり、「短いが伝わっていない」が通る。
//
// 代わりに**厚みの勾配**を置く。**プレイヤーは物語を読みに来たのではなく、
// ゲームをしに来ている。**
//
//   Stage 0   … 一番薄い。まだ何も分かっていない人を待たせない
//   Stage 1〜3 … 人が増えるぶん厚くする。ここで初めて関係が動く
//   根城       … 一番厚い。**読みに行った人だけが開く場面**なので、長くてよい
//
// 「もう終わり？ もっと読みたいのに」で切り上げるのが正しいのは、序盤の話である。
//
// **属性を台詞で説明しない。**「私は賢いです」を言わせない。ヒバナは話す速度で、
// ツグミは観察の細かさで、ナギは手が止まらないことで、ゲンゾウは間の長さで見せる。
//
// **深さにも勾配を置く（R15・作者判断）。**厚み（行数）とは別の軸である。
// 望み・秘密・過去・後悔は**五人が揃ってから**出す。Stage 0 でそれを出すと、
// まだ誰のことも知らない読み手に重さだけが渡り、**人物の調子が沈む。**
// 立ち上がりで沈んだゴウは「無口で頼れる人」に読めるが、**それは別人である**
// （設定は「声がでかい。ガサツで、口が上手くて、調子がいい」）。
//
//   Stage 0   … 二人の**調子**だけ。掘らない
//   Stage 1〜3 … 関係が動く。ここから望みに触れてよい
//   根城       … 一番深い。秘密と過去はここに置く
//
// **人物はゲームのシステムを知らない。**彼らはそこに生きているだけで、
// 腕力・集中・受け・行動権・反応点・隊列・後列減衰・手番といった語は、
// **一人も知らないし、一度も使わない。**知っているのは坑の側の事実だけである
// （先見機で次の一戦が読めること、外へ出ると遠征の記憶が崩れること、遺装が崩れること）。
//
// **言い換えても駄目である（R16追補・作者指摘）。**語彙一覧に無いだけで、中身が仕様なら同じこと。
//
//   × 「火力とか、無いですけど」                    … damage の役割分担
//   ○ 「押し返すだけで、倒せた試しが無いんですけど」 … ナギが自分について知っている事実
//   × 「戻せるのは、いま受けたぶんだけです」         … 回復量の上限
//   ○ 「塞げるのは開いたばかりのものだけです」       … 医者が手でできること
//   × 「あたしが先に行くと、みんな早くなるの？」     … 手番の勘定
//   ○ 「あたしが先に行くと、みんな殴られないの？」   … ヒバナが見ている光景
//
// **そもそも、いま言う必要があるか（R16追補・作者指摘）。**言い換えても、条件や上限を
// 並べていれば説明である。ナギを誘う場面でツグミが言うべきなのは、治療の適用範囲ではなく
// 「傷はわたしが診ますから、安心して前に立ってください」だけである。
//
// **同じことを三度言い直さない（R16追補・作者指摘）。**「なあ、すげえだろ。自分でも
// すげえと思ってるだろ」「かけたよな？ かけた。俺がかけた。かけたはずだ」は、
// **コントの喋り方**であって、ゴウの減らず口ではない。押しの強さは一度で出す。
//
// 盤面の理屈を伝えたいときは、**規則ではなく観察を言わせる。**
//
//   × 「あなたの受けは一発ごとに引きます」      … guard の仕様
//   ○ 「細かいのを何発もらっても、傷が浅い。数えました」 … ツグミが見た事実
//   × 「後ろが一手ぶん得をします」              … 手番の勘定
//   ○ 「灰殻が揃ってそちらを向きます。その隙に、後ろが動けています」
//
// **数値と仕様を書く場所は台詞ではない。**名簿（character-lore.mjs の field）、
// footer / hint、技能説明はゲームがプレイヤーへ直接話す欄なので、そちらで書く。
//
// ---------------------------------------------------------------- R16 で Stage 1〜3 と根城を張り直した
//
// R15 は「調子」の直しを **Stage 0 の8断片にしか適用していなかった**（HISTORY §3.8 / §3.10）。
// 残り21断片は R13 のままで、作者評価は「性格に合っていない／知らないはずの情報を
// 知っている」だった。数えると出る。
//
//   ゴウ  Stage 0 … 22行・平均24字      ← R15 で直した側
//   ゴウ  Stage 1 …  6行・平均13字（うち5行が12字以下）
//   ゴウ  Stage 3 …  3行・平均14字
//
// 「ナギ、前。」「断らないから。」「名前は。」「照会は。」「ないな。」は、**R15 が
// 消したはずの寡黙で有能な隊長**である。設定は「だいたい何か言いながら前に出る」。
// 同じ形で、ナギは19行中9行が「……」始まりで worry / hurt / shock しか持たず、
// ゲンゾウは16行中12行が calm だった。**一面だけが実装されていた。**
//
// **人物ごとに「毎回出る癖」を一つ決めて、全断片へ通す。**
//
//   ゴウ    … 短く切らない。何か言いながら動く。困ると逸らす。押し切られたら「へいへい」。
//             **素直になるのは、流した先で誰かが傷ついたときだけ**（滅多に無い）
//   ツグミ  … 「——」で被せる。言い過ぎて、その場で後悔する（「……あ。すみません、言い方が」）。
//             **数を突きつけない（R16追補・作者指摘）。**初稿は「二寸浅いです」「四回目です」
//             「ちなみに十三です」と、寸法や回数を相手へ返す癖にしていた。**嫌な奴に見える。**
//             見ているものは同じでも、目盛りではなく**体と出来事の側**で言う
//             （朝は耳まで／いまは肩、前も、その前も）。「あと三分」は先見機の校正時間で
//             会話の筋そのものなので、そこだけ残す
//   ナギ    … 愚痴りながら**手だけは止まらない**。褒められると壊れる
//   ヒバナ  … 返事を待たない。全部感嘆。前の場面を忘れている
//   ゲンゾウ… 敬称と間。ただし calm 以外も混ぜる。甘いもの。若者言葉に必ず失敗する
//
// ---- 誰がいつ何を知っているか（R16）----------------------------------------
//
// **知識の矛盾は「性格の崩れ」と同じ原因から出る。**書く順ではなく、人物の側の
// 都合で情報を置くと、両方が同時に壊れる。R16 で直した4件を、そのまま規約にする。
//
//   1. **巻き戻りを覚えているのはゴウだけ。**ツグミは巻き戻り前を自分から語らない。
//      彼女が拾えるのは**ゴウの様子**であり、そこから訊いて、ゴウが認める
//      （`stage_0_prologue_win`）。**先に答えを台詞で渡さない**のは §6.4 のままである。
//   2. **ヒバナの歳は本人の申告。**誰かが先に「十一」と言えば、それは知り得ない。
//      申告は根城の `homestead_thick_book` にある。
//   3. **照会は坑の中では返らない。**紙に訊いて、紙が返るまで一往復かかる。
//      投げるのが `stage_2_join`、返るのが `stage_2_end`（詰所）である。
//   4. **ゲンゾウはその照会を読んで来た。**十三号室からの二件——記録の無い子と、
//      五年前に戻らなかった者——が、彼が戸を叩く理由であり、`stage_3_act2` の
//      「お兄様は、ご存命ですよ」と `homestead_thick_book` の「先日」の根拠でもある。
//   5. **先見機が読めた内容に、人物は驚かない。**予測は次の一戦の個体・並び・
