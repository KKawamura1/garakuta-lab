const freezeLore = (entry) => Object.freeze({
  ...entry,
  figure: Object.freeze([...(entry.figure ?? [])]),
  field: Object.freeze([...(entry.field ?? [])]),
  home: Object.freeze([...(entry.home ?? [])]),
  will: Object.freeze([...(entry.will ?? [])]),
  bonds: Object.freeze((entry.bonds ?? []).map((bond) => Object.freeze({
    ...bond,
    lines: Object.freeze([...(bond.lines ?? [])]),
  }))),
});

export const CHARACTER_LORE = Object.freeze(
  Object.fromEntries(Object.entries(CHARACTER_LORE_RAW).map(([id, entry]) => [id, freezeLore(entry)])),
);

export const CHARACTER_NAMES = Object.freeze(
  Object.fromEntries(
    Object.entries(CHARACTER_LORE).map(([id, entry]) => [id, entry.name + " — " + entry.epithet]),
  ),
);

export function characterLoreFor(characterId) {
  return CHARACTER_LORE[characterId] ?? null;
}
